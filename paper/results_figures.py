#!/usr/bin/env python3
"""Paper figures and tables for the results section.

  python3 paper/results_figures.py

Input : results/reports/full-contention/results.csv (all 2,814 instances, every algorithm run in the
        same benchmark run). Makespans are identical to the full-all-instances-v2 report; the
        contention columns are not used. Only the .md and .tex tables are committed; the figures and
        .csv files are regenerated by this script.
Output: paper/results/
  fig_<metric>_vs_<x>_workflows.{png,pdf}   six panels: Montage, Genome, LIGO, FFT, GE, LA
  fig_<metric>_vs_<x>_random.{png,pdf}      three panels: random graphs at CCR 0.1, 1, 10
  fig_gain_by_ccr.{png,pdf}                 DSLA's mean gain over each baseline per CCR
  tab_pairwise.{md,csv,tex}                 DSLA vs each baseline: better / equal / worse % per family + Combined
  tab_average_makespan.{md,csv,tex}         average makespan per family (+ workflows, random, all)
  tab_efficiency_by_p.{md,csv}              efficiency per processor count, DSLA and the baselines' mean
  tab_gain_by_characteristics.{md,csv}      DSLA's gain over the best baseline per CCR, beta, size and p
  tab_significance.md, tab_significance_by_family.md   Wilcoxon + Friedman / Nemenyi for this set
  tab_runtime.{md,csv}                      mean wall time per run (s) per task count, random graphs; includes
                                            process start and reading the n x n input, so it is not a fair
                                            comparison of the scheduling work itself
metric = makespan, slr, speedup, efficiency; x = tasks, processors.
Needs pandas, matplotlib, numpy.
"""
import os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "results", "reports", "full-contention", "results.csv")
OUT = os.path.join(HERE, "results")

# benchmark id -> paper name: DSLA and the six baselines compared in the paper. The other algorithms in
# the benchmark (PEFT, IPEFT, MPEFT, LSTD, BPPTS, LEFT-D, OPPTS) are discussed in the related work only;
# add them here to include them in the figures and tables.
NAMES = {"dsla": "DSLA", "heft": "HEFT", "ppts": "PPTS", "ippts": "IPPTS", "pmms": "PMMS", "aeft": "AEFT",
         "left": "LEFT"}
ALIAS = {"z_best10": "dsla"}       # the benchmark run used DSLA's lab id (identical schedules)
WORKFLOWS = ["Montage", "Genome", "LIGO", "FFT", "GE", "LA"]
CCRS = ["0.1", "1", "10"]

PALETTE = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
GRAYS = ["#52514e", "#8a8984", "#b4b3ad"]
MARKERS = ["o", "s", "^", "D", "v", "P", "X", "<", ">", "h", "*", "p", "d", "8"]
plt.rcParams.update({"font.size": 8.5, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.edgecolor": "#8a8984", "xtick.color": "#52514e", "ytick.color": "#52514e",
                     "axes.grid": True, "grid.color": "#e6e5e0", "grid.linewidth": 0.6,
                     "legend.frameon": False, "figure.dpi": 150, "savefig.dpi": 300})


def load():
    d = pd.read_csv(SRC)
    d["algo"] = d.algo.replace(ALIAS)
    d = d[d.algo.isin(NAMES) & d.status.isin(["ok", "unchecked"])].copy()
    ok = d.groupby("path").algo.nunique()
    d = d[d.path.isin(ok[ok == len(NAMES)].index)]
    d["name"] = d.algo.map(NAMES)
    d["group"] = np.where(d.family.str.startswith("R-"), "random", "workflow")
    r = d.family.str.extract(r"R-ccr([\d.]+)-b([\d.]+)")
    d["ccr"], d["beta"] = r[0], r[1]
    return d


def order(d):
    """DSLA first, then baselines by overall average makespan (best first)."""
    m = d.groupby("name").makespan.mean().drop("DSLA").sort_values()
    return ["DSLA"] + list(m.index)


def styles(names):
    s = {}
    for i, n in enumerate(names):
        if i == 0:
            s[n] = dict(color="#0b0b0b", marker="o", ls="-", lw=2.2, ms=4.6, zorder=10)
        else:
            j = i - 1
            col = PALETTE[j] if j < len(PALETTE) else GRAYS[(j - len(PALETTE)) % len(GRAYS)]
            s[n] = dict(color=col, marker=MARKERS[i % len(MARKERS)], ls="-" if j < len(PALETTE) else "--",
                        lw=1.1, ms=3.4, zorder=3)
    return s


def save(fig, name):
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(OUT, f"{name}.{ext}"), bbox_inches="tight")
    plt.close(fig)


def panels(d, names, metric, by, panels_spec, title_fmt, name, ylab):
    st = styles(names)
    k = len(panels_spec); cols = 3; rows = -(-k // cols)
    fig, axes = plt.subplots(rows, cols, figsize=(7.2, 2.25 * rows + 0.75), squeeze=False)
    for ax, (label, sub) in zip(axes.flat, panels_spec):
        t = sub.groupby([by, "name"])[metric].mean().unstack()
        xs = list(t.index)
        for n in reversed(names):
            ax.plot(range(len(xs)), t[n].values, label=n, **st[n])
        many = len(xs) > 6
        ax.set_xticks(range(len(xs)), [str(x) for x in xs], rotation=45 if many else 0,
                      ha="right" if many else "center", rotation_mode="anchor")
        ax.set_title(title_fmt.format(label), loc="left", fontsize=9)
        ax.set_xlabel("Number of tasks" if by == "nodes" else "Number of processors")
        ax.set_ylabel(ylab)
        ax.tick_params(axis="x", labelsize=7 if many else 7.5)
    for ax in list(axes.flat)[k:]:
        ax.axis("off")
    h, l = axes.flat[0].get_legend_handles_labels()
    idx = [l.index(n) for n in names]
    fig.tight_layout()
    fig.subplots_adjust(top=1 - 0.62 / fig.get_size_inches()[1])
    fig.legend([h[i] for i in idx], [l[i] for i in idx], loc="upper center", ncol=7, fontsize=7.5,
               bbox_to_anchor=(0.5, 1.0), handlelength=2.2, columnspacing=1.0)
    save(fig, name)


def figures(d, names):
    wf = [(f, d[d.family == f]) for f in WORKFLOWS]
    rnd = [(c, d[d.ccr == c]) for c in CCRS]
    specs = [("makespan", "Average makespan"), ("slr", "Average SLR"), ("speedup", "Average speedup"),
             ("efficiency", "Average efficiency")]
    for metric, ylab in specs:
        for by, x in (("nodes", "tasks"), ("p", "processors")):
            panels(d, names, metric, by, wf, "{}", f"fig_{metric}_vs_{x}_workflows", ylab)
            panels(d, names, metric, by, rnd, "Random graphs, CCR = {}", f"fig_{metric}_vs_{x}_random", ylab)


def write(t, name, tex=True, fmt="{:.2f}"):
    t.to_csv(os.path.join(OUT, name + ".csv"))
    open(os.path.join(OUT, name + ".md"), "w").write(t.to_markdown(floatfmt=fmt[2:-1]) + "\n")
    if tex:
        open(os.path.join(OUT, name + ".tex"), "w").write(
            t.to_latex(float_format=lambda v: fmt.format(v), escape=True))


def pairwise(d, names):
    m = d.pivot_table(index=["family", "path"], columns="name", values="makespan")
    rows = []
    groups = [(f, m.loc[[f]]) for f in WORKFLOWS] + \
             [("Random", m[m.index.get_level_values(0).str.startswith("R-")]), ("Combined", m)]
    for b in names[1:]:
        row = {"versus": b}
        for g, s in groups:
            diff = s["DSLA"] - s[b]
            row[(g, "better")] = 100 * (diff < 0).mean()
            row[(g, "equal")] = 100 * (diff == 0).mean()
            row[(g, "worse")] = 100 * (diff > 0).mean()
        rows.append(row)
    t = pd.DataFrame(rows).set_index("versus")
    t.columns = pd.MultiIndex.from_tuples(t.columns)
    t.to_csv(os.path.join(OUT, "tab_pairwise.csv"))
    # compact form: one cell per family, "better / equal / worse" in percent
    c = pd.DataFrame({g: [f"{t.loc[b, (g, 'better')]:.1f} / {t.loc[b, (g, 'equal')]:.1f} / {t.loc[b, (g, 'worse')]:.1f}"
                          for b in t.index] for g, _ in groups}, index=t.index)
    c.index.name = "DSLA vs"
    open(os.path.join(OUT, "tab_pairwise.md"), "w").write(
        "Percentage of instances on which DSLA's makespan is shorter / equal / longer.\n\n" + c.to_markdown() + "\n")
    open(os.path.join(OUT, "tab_pairwise.tex"), "w").write(c.to_latex(escape=True))
    return t


def averages(d, names):
    t = d.pivot_table(index="family", columns="name", values="makespan")[names]
    t = t.reindex(WORKFLOWS + sorted(f for f in t.index if f.startswith("R-")))
    t.loc["All workflows"] = d[d.group == "workflow"].groupby("name").makespan.mean()[names]
    t.loc["All random"] = d[d.group == "random"].groupby("name").makespan.mean()[names]
    t.loc["All instances"] = d.groupby("name").makespan.mean()[names]
    write(t.T, "tab_average_makespan", fmt="{:.1f}")


def efficiency(d, names):
    rows = []
    for g, sub in (("workflows", d[d.group == "workflow"]), ("random", d[d.group == "random"])):
        e = sub.groupby(["p", "name"]).efficiency.mean().unstack()
        for p, r in e.iterrows():
            base = r[names[1:]]
            rows.append({"graphs": g, "p": p, "DSLA": r["DSLA"], "baseline mean": base.mean(),
                         "best baseline": base.max(), "DSLA speedup": sub[(sub.p == p) & (sub.name == "DSLA")].speedup.mean()})
    t = pd.DataFrame(rows).set_index(["graphs", "p"])
    write(t, "tab_efficiency_by_p", tex=False)


def characteristics(d, names):
    m = d.pivot_table(index="path", columns="name", values="makespan")
    vbest = m[names[1:]].min(axis=1)
    info = d[d.name == "DSLA"].set_index("path")[["family", "group", "ccr", "beta", "nodes", "p"]]
    g = info.join(m)
    g["vgain"] = 100 * (vbest - m["DSLA"]) / vbest
    rows = []
    specs = (("ccr", "CCR (random graphs)", "random"), ("beta", "heterogeneity beta (random graphs)", "random"),
             ("nodes", "tasks (workflows)", "workflow"), ("nodes", "tasks (random graphs)", "random"),
             ("p", "processors (workflows)", "workflow"), ("p", "processors (random graphs)", "random"))
    for col, label, grp in specs:
        for v, s in g[g.group == grp].groupby(col):
            strongest = s[names[1:]].mean().idxmin()           # baseline with the lowest average here
            gain = 100 * (s[strongest] - s["DSLA"]) / s[strongest]
            rows.append({"characteristic": label, "value": v, "instances": len(s),
                         "strongest baseline": strongest,
                         "mean gain vs strongest %": gain.mean(),
                         "DSLA shorter vs strongest %": 100 * (gain > 0).mean(),
                         f"mean gain vs per-instance best of {len(names) - 1} %": s.vgain.mean()})
    t = pd.DataFrame(rows).set_index(["characteristic", "value"])
    write(t, "tab_gain_by_characteristics", tex=False)
    return t


def runtime(d, names):
    sub = d[d.group == "random"]
    t = sub.pivot_table(index="name", columns="nodes", values="runtime_s", aggfunc="mean").reindex(names)
    t["all instances"] = d.groupby("name").runtime_s.mean().reindex(names)
    write(t, "tab_runtime", tex=False, fmt="{:.4f}")


def gain_by_ccr(d, names):
    m = d[d.group == "random"].pivot_table(index=["ccr", "path"], columns="name", values="makespan")
    fig, ax = plt.subplots(figsize=(7.0, 2.8))
    base = names[1:]; w = 0.26
    for i, c in enumerate(CCRS):
        s = m.loc[c]
        g = [100 * ((s[b] - s["DSLA"]) / s[b]).mean() for b in base]
        ax.bar(np.arange(len(base)) + (i - 1) * w, g, w, label=f"CCR = {c}", color=PALETTE[i])
    ax.axhline(0, color="#52514e", lw=0.8)
    ax.set_xticks(range(len(base)), base, rotation=35, ha="right")
    ax.set_ylabel("Mean makespan reduction of DSLA (%)")
    ax.grid(axis="x", visible=False)
    ax.legend(ncol=3, fontsize=8, loc="upper left", frameon=False)
    fig.tight_layout()
    save(fig, "fig_gain_by_ccr")


def significance(d, names):
    """Wilcoxon (DSLA vs each baseline, Holm-corrected, also per DAG) and Friedman / Nemenyi."""
    import sys
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from stats import significance_tables
    c = d.assign(algo=d.name)
    sig = significance_tables(c, names, "DSLA")
    open(os.path.join(OUT, "tab_significance.md"), "w").write(sig["_markdown"] + "\n")
    if "Wilcoxon_by_family" in sig:
        f = sig["Wilcoxon_by_family"].reset_index()
        f["family"] = pd.Categorical(f.family, WORKFLOWS + sorted(x for x in f.family.unique() if x not in WORKFLOWS))
        f = f.sort_values(["family", "versus"]).set_index(["family", "versus"])
        open(os.path.join(OUT, "tab_significance_by_family.md"), "w").write(
            "DSLA vs each baseline per family (Wilcoxon signed-rank, Holm-corrected within the family).\n\n"
            + f.to_markdown(floatfmt=".3g") + "\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    d = load()
    names = order(d)
    print(f"{d.path.nunique()} instances, {len(names)} algorithms: {', '.join(names)}")
    figures(d, names)
    pairwise(d, names)
    averages(d, names)
    efficiency(d, names)
    characteristics(d, names)
    runtime(d, names)
    gain_by_ccr(d, names)
    significance(d, names)
    print("written to", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
